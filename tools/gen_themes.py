#!/usr/bin/env python3
"""Generate theme resources from a palette file.

A theme is `themes/<name>.yml`: a shape, a day palette and a night palette. This script
writes the drawables and the two styles, so the XML is never edited by hand.

Usage:
    python3 tools/gen_themes.py            # write the resources
    python3 tools/gen_themes.py --check    # fail if the output is stale
"""
import argparse
import math
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEMES = ROOT / "themes"
RES = ROOT / "app" / "src" / "main" / "res"
HEADER = "<!-- Generated by tools/gen_themes.py from {source}. Do not edit. -->"


def slug(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def dial(palette, shape, size=480):
    r = size // 2
    face_r = r - 20
    inner_r = face_r - shape["ring_width"] - 8
    return f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
    <path
        android:fillColor="{palette['face']}"
        android:pathData="M{r},{r}m-{face_r},0a{face_r},{face_r} 0,1 1,{face_r * 2} 0a{face_r},{face_r} 0,1 1,-{face_r * 2} 0" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="{palette['ring']}"
        android:strokeWidth="{shape['ring_width']}"
        android:pathData="M{r},{r}m-{face_r},0a{face_r},{face_r} 0,1 1,{face_r * 2} 0a{face_r},{face_r} 0,1 1,-{face_r * 2} 0" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="{palette['ring']}"
        android:strokeWidth="2"
        android:pathData="M{r},{r}m-{inner_r},0a{inner_r},{inner_r} 0,1 1,{inner_r * 2} 0a{inner_r},{inner_r} 0,1 1,-{inner_r * 2} 0" />
</vector>
"""


def background(palette, width=800, height=400):
    return f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width}dp"
    android:height="{height}dp"
    android:viewportWidth="{width}"
    android:viewportHeight="{height}">
    <path
        android:fillColor="{palette['surface']}"
        android:pathData="M0,0h{width}v{height}h-{width}z" />
</vector>
"""


def stopwatch(palette, shape, size=480):
    r = size // 2
    face_r = r - 30
    return f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
    <path
        android:fillColor="{palette['face']}"
        android:pathData="M{r},{r}m-{face_r},0a{face_r},{face_r} 0,1 1,{face_r * 2} 0a{face_r},{face_r} 0,1 1,-{face_r * 2} 0" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="{palette['ring']}"
        android:strokeWidth="{shape['ring_width']}"
        android:pathData="M{r},{r}m-{face_r},0a{face_r},{face_r} 0,1 1,{face_r * 2} 0a{face_r},{face_r} 0,1 1,-{face_r * 2} 0" />
</vector>
"""


def thumb(palette, shape, size=128):
    r = size // 2
    face_r = r - 6
    ang = math.radians(150 + 240 * 0.62)
    x = r + int((face_r - 8) * math.cos(ang))
    y = r + int((face_r - 8) * math.sin(ang))
    return f"""<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{size}"
    android:viewportHeight="{size}">
    <path
        android:fillColor="{palette['face']}"
        android:pathData="M{r},{r}m-{face_r},0a{face_r},{face_r} 0,1 1,{face_r * 2} 0a{face_r},{face_r} 0,1 1,-{face_r * 2} 0" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="{palette['ring']}"
        android:strokeWidth="4"
        android:pathData="M{r},{r}m-{face_r},0a{face_r},{face_r} 0,1 1,{face_r * 2} 0a{face_r},{face_r} 0,1 1,-{face_r * 2} 0" />
    <path
        android:fillColor="#00000000"
        android:strokeColor="{palette['needle']}"
        android:strokeWidth="4"
        android:pathData="M{r},{r}L{x},{y}" />
</vector>
"""


def style(name, palette, suffix, slug_name):
    night = suffix == "night"
    return f"""    <style name="AppTheme.{name}{'' if not night else '.Night'}" parent="AppTheme">
        <item name="themedCarBackground">@drawable/bg_{slug_name}_{suffix}</item>
        <item name="themedDialBackground">@drawable/dial_{slug_name}_{suffix}</item>
        <item name="themedEmptyDialBackground">@drawable/dial_{slug_name}_{suffix}</item>
        <item name="themedBlankDialBackground">@drawable/dial_{slug_name}_{suffix}</item>
        <item name="themedNeedle">@drawable/needle_dark</item>
        <item name="themedStopWatchBackground">@drawable/sw_{slug_name}_{suffix}</item>
        <item name="themedNeedleColor">{palette['needle']}</item>
        <item name="themedPaletteSurface">{palette['surface']}</item>
        <item name="themedPaletteFace">{palette['face']}</item>
        <item name="themedPaletteRing">{palette['ring']}</item>
        <item name="themedPaletteTick">{palette['tick']}</item>
        <item name="themedPaletteAccent">{palette['accent']}</item>
        <item name="themedPaletteMark">{palette['ring']}</item>
        <item name="sv_speedometerColor">{palette['ring']}</item>
        <item name="sv_speedometerBackColor">{palette['face']}</item>
        <item name="sv_indicator">HalfLineIndicator</item>
        <item name="sv_indicatorWidth">2dp</item>
        <item name="sv_tickPadding">0dp</item>
        <item name="sv_tickRotation">false</item>
    </style>
"""


def build():
    files = {}
    styles = ["<resources>"]
    entries = []
    for path in sorted(THEMES.glob("*.yml")):
        data = yaml.safe_load(path.read_text())
        name = data["name"]
        shape = data["shape"]
        s = slug(name)
        source = f"themes/{path.name}"
        for mode in ("day", "night"):
            palette = data[mode]
            files[f"drawable/dial_{s}_{mode}.xml"] = HEADER.format(source=source) + "\n" + dial(palette, shape)
            files[f"drawable/bg_{s}_{mode}.xml"] = HEADER.format(source=source) + "\n" + background(palette)
            files[f"drawable/sw_{s}_{mode}.xml"] = HEADER.format(source=source) + "\n" + stopwatch(palette, shape)
            styles.append(style(name, palette, mode, s))
        files[f"drawable/ic_theme_{s}.xml"] = HEADER.format(source=source) + "\n" + thumb(data["day"], shape)
        styles.append("</resources>")
        entries.append(name)
    files[f"values/themes_generated.xml"] = "\n".join(styles) + "\n"
    return files, entries


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    files, entries = build()
    stale = []
    for relative, content in files.items():
        target = RES / relative
        if not target.exists() or target.read_text() != content:
            stale.append(relative)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
    if args.check and stale:
        print("stale theme resources:", ", ".join(stale))
        return 1
    print("themes:", ", ".join(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
