#!/usr/bin/env python3
"""Generate docs/generated/inventory.md from the app sources.

CI regenerates this file and commits it. Do not edit the output by hand.

Usage:
    python3 tools/gen_inventory.py            # write the file
    python3 tools/gen_inventory.py --check    # exit 1 when the file is stale
"""

import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_ROOT = ROOT / "app" / "src" / "main" / "java"
OUTPUT = ROOT / "docs" / "generated" / "inventory.md"
SOURCE_SUFFIXES = {".kt", ".java"}
GENERATED_MARK = "<!-- generated by tools/gen_inventory.py: do not edit -->"


def count_lines(path: pathlib.Path) -> int:
    with path.open("r", encoding="utf-8", errors="replace") as handle:
        return sum(1 for _ in handle)


def collect() -> list[tuple[str, str, int]]:
    rows = []
    for path in sorted(SOURCE_ROOT.rglob("*")):
        if path.suffix not in SOURCE_SUFFIXES or not path.is_file():
            continue
        relative = path.relative_to(SOURCE_ROOT)
        rows.append((relative.parent.as_posix(), relative.name, count_lines(path)))
    return rows


def render(rows: list[tuple[str, str, int]]) -> str:
    packages: dict[str, list[tuple[str, int]]] = {}
    for package, name, lines in rows:
        packages.setdefault(package, []).append((name, lines))

    kotlin = sum(1 for row in rows if row[1].endswith(".kt"))
    java = len(rows) - kotlin
    total = sum(row[2] for row in rows)

    out = [
        GENERATED_MARK,
        "",
        "# Source inventory",
        "",
        "Every source file under `app/src/main/java`, grouped by package. CI regenerates",
        "this file on each push, so it always matches the tree.",
        "",
        f"- Files: {len(rows)} ({kotlin} Kotlin, {java} Java)",
        f"- Lines: {total}",
        f"- Packages: {len(packages)}",
        "",
    ]
    for package in sorted(packages):
        entries = sorted(packages[package])
        out.append(f"## `{package}`")
        out.append("")
        out.append("| File | Lines |")
        out.append("|---|---|")
        for name, lines in entries:
            out.append(f"| `{name}` | {lines} |")
        out.append("")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 when the committed file is out of date",
    )
    args = parser.parse_args()

    content = render(collect())
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/gen_inventory.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is current")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
